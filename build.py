#!/usr/bin/python3
"""Generates the GitHub Actions workflow in .github/workflows/build.yml."""

from pathlib import Path

SUPPORTED_FEDORA_VERSIONS: list[int] = [45]
SUPPORTED_JAVA_VERSIONS: list[int] = [25]
MANDREL_VERSION: str = "25.0.5.0-Final"
IMAGES: list[str] = [
    "mercur3/quarkus-native-builder",
    "ghcr.io/mercur3/quarkus-native-builder",
]
OUTPUT_FILE: Path = Path(".github/workflows/build.yml")

HEADER = """\
###############################################################################
# WARNING                                                                     #
# This file is autogenerated. Do NOT edit this file. Run =./build.py= instead #
###############################################################################

name: Build & Push Quarkus Native Builder

on:
  push:
    branches:
      - master
  pull_request:
    branches:
      - master

# Cancel superseded runs of the same PR (equivalent of Azure's `autoCancel`)
concurrency:
  group: ${{ github.workflow }}-${{ github.ref }}
  cancel-in-progress: ${{ github.event_name == 'pull_request' }}

permissions:
  contents: read
  packages: write  # lets GITHUB_TOKEN push to ghcr.io

jobs:
  build:
    name: Build & Push ${{ matrix.tag }}
    runs-on: ubuntu-latest
    strategy:
      fail-fast: false
      matrix:
        include:
"""

FOOTER = """\

    steps:
      - name: Checkout
        uses: actions/checkout@v4

      - name: Configure Dockerfile
        env:
          FEDORA_VERSION: ${{ matrix.fedora_version }}
          MANDREL_VERSION: ${{ matrix.mandrel_version }}
          JAVA_VERSION: ${{ matrix.java_version }}
        run: |
          echo "Building on Fedora $FEDORA_VERSION, Mandrel $MANDREL_VERSION, Java $JAVA_VERSION"
          echo "Using $(nproc) threads"
          echo "------------------------------------------------------"
          sed "s/__fedora_version__/$FEDORA_VERSION/g"   -i Dockerfile
          sed "s/__mandrel_version__/$MANDREL_VERSION/g" -i Dockerfile
          sed "s/__java_version__/$JAVA_VERSION/g"       -i Dockerfile
          cat Dockerfile

      - name: Set up Docker Buildx
        uses: docker/setup-buildx-action@v3

      # Token based authentication: DOCKERHUB_TOKEN is a Docker Hub access token
      # (Account settings -> Personal access tokens), NOT the account password.
      - name: Log in to Docker Hub
        if: github.event_name != 'pull_request'
        uses: docker/login-action@v3
        with:
          username: ${{ secrets.DOCKERHUB_USERNAME }}
          password: ${{ secrets.DOCKERHUB_TOKEN }}

      # Token based authentication: the built-in GITHUB_TOKEN, no extra secret needed.
      - name: Log in to GitHub Container Registry
        if: github.event_name != 'pull_request'
        uses: docker/login-action@v3
        with:
          registry: ghcr.io
          username: ${{ github.actor }}
          password: ${{ secrets.GITHUB_TOKEN }}

      - name: Build & Push ${{ matrix.tag }}
        uses: docker/build-push-action@v6
        with:
          # Explicit local context so the sed-patched Dockerfile is the one used
          context: .
          file: Dockerfile
          push: ${{ github.event_name != 'pull_request' }}
          tags: |
%(tags)s
"""


def main() -> None:
    output = HEADER
    for f in SUPPORTED_FEDORA_VERSIONS:
        for j in SUPPORTED_JAVA_VERSIONS:
            output += f"""\
          - fedora_version: '{f}'
            mandrel_version: '{MANDREL_VERSION}'
            java_version: '{j}'
            tag: 'f{f}-j{j}'
"""
    tags = [
        f"            {image}:{tag}"
        for image in IMAGES
        for tag in ("${{ matrix.tag }}", "latest")
    ]
    output += FOOTER % {"tags": "\n".join(tags)}

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(output)


if __name__ == "__main__":
    main()

